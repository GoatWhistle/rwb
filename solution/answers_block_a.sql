-- 2. Топ-10 продавцов по выручке
--    Контроль: у первого 226 987.93
--
-- Разбор по словам:
--   FROM core.order_items i — идём ОТ позиций, не от заказов: выручка
--                          продавца складывается из его строк. В заказе
--                          бывают товары разных продавцов, сумма целого
--                          заказа продавцу не принадлежит.
--   JOIN core.orders o   — приклеиваем заказ ради статуса. Внутренний JOIN
--                          безопасен: позиций без заказа в данных нет.
--   JOIN core.sellers s  — приклеиваем продавца ради города и штата.
--   WHERE o.status = 'delivered' — фильтр строк ДО подсчёта: дальше идут
--                          только позиции доставленных заказов.
--   count(DISTINCT i.order_id) — в скольких разных заказах были его товары.
--   count(*)             — число строк группы; одна строка = одна единица
--                          товара, то есть «сколько единиц продал».
--   sum(i.price) AS revenue — сумма цен только его позиций; AS revenue —
--                          имя колонки, по нему же сортируем.
--   GROUP BY s.seller_id, s.city, s.state — одна группа = один продавец.
--                          Город и штат перечислены, потому что всё из
--                          SELECT вне агрегатов обязано быть в GROUP BY.
--   ORDER BY revenue DESC — DESC (descending) — по убыванию: крупный сверху.
--   LIMIT 10             — показать только первые 10 строк.
-- ------------------------------------------------------------
SELECT
    s.seller_id,
    s.city,
    s.state,
    count(DISTINCT i.order_id) AS orders_cnt,
    count(*)                   AS units,
    sum(i.price)               AS revenue
FROM core.order_items i
JOIN core.orders  o USING (order_id)
JOIN core.sellers s USING (seller_id)
WHERE o.status = 'delivered'
GROUP BY s.seller_id, s.city, s.state
ORDER BY revenue DESC
LIMIT 10;

