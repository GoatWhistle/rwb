-- 5. Выручка по категориям
--    Товары без категории не выбрасываем — отдельная строка,
--    иначе сумма не сойдётся с общей выручкой.
--    Контроль: 74 категории, топ 1 233 131.72, итого 13 221 498.11
--
-- Разбор по словам:
--   coalesce(p.category_name, '(без категории)') — «если категория пустая
--                          (NULL) — подставить подпись». Так 610 товаров
--                          без категории образуют собственную строку,
--                          а не исчезают вместе со 170 тыс. выручки.
--   JOIN core.products p — приклеиваем карточку товара ради категории;
--                          позиций без товара нет, внутренний JOIN безопасен.
--   WHERE o.status = 'delivered' — то же определение выручки, что везде.
--   sum(i.price) AS revenue — выручка категории.
--   sum(sum(i.price)) OVER () — самое хитрое место. Внутренний sum —
--                          выручка категории (после группировки). Внешний
--                          sum(…) OVER () — ОКОННАЯ функция: проходит по уже
--                          сгруппированным строкам и складывает их все.
--                          OVER () с пустыми скобками = «окно — весь
--                          результат». Итог: в каждой строке рядом с выручкой
--                          категории доступна общая — и можно поделить.
--   100 * … / …          — доля категории в процентах от общей выручки.
--   GROUP BY 1           — группировка по первой колонке: названию категории
--                          (уже с подставленной подписью для пустых).
--   ORDER BY revenue DESC — крупнейшие сверху.
-- ------------------------------------------------------------
SELECT
    coalesce(p.category_name, '(без категории)') AS category,
    sum(i.price)                                 AS revenue,
    round(100 * sum(i.price) / sum(sum(i.price)) OVER (), 2) AS revenue_pct
FROM core.order_items i
JOIN core.orders   o USING (order_id)
JOIN core.products p USING (product_id)
WHERE o.status = 'delivered'
GROUP BY 1
ORDER BY revenue DESC;
