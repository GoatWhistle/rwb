-- 4. Покупатели и повторные покупки
--    Человек = customer_unique_id, не customer_id.
--    Контроль: 96 096 покупателей, вернулись 3.12%
--
-- Разбор по словам:
--   WITH per_customer AS (…) — первая ступень: одна строка на человека
--                          с числом его заказов.
--   GROUP BY customer_unique_id — группируем по стабильному идентификатору
--                          человека. Возьми тут customer_id — у каждого
--                          «покупателя» оказался бы ровно один заказ
--                          и повторных не нашлось бы вовсе.
--   count(*)             — во внешнем запросе считает строки per_customer,
--                          то есть людей: 96 096.
--   count(*) FILTER (WHERE orders_cnt >= 2) — тот же счётчик, но через
--                          фильтр проходят только люди с 2+ заказами.
--   100.0 * … / count(*) — доля в процентах. 100.0 именно с точкой:
--                          целое на целое SQL делит с отбрасыванием дробной
--                          части и выдал бы 0; дробное число в формуле
--                          переводит весь расчёт в дробные.
--   round(…, 2)          — до сотых процента: 3.12.
-- ------------------------------------------------------------
WITH per_customer AS (
    SELECT customer_unique_id, count(*) AS orders_cnt
    FROM core.orders
    GROUP BY 1
)
SELECT
    count(*)                                   AS customers_total,
    count(*) FILTER (WHERE orders_cnt >= 2)    AS returned,
    round(100.0 * count(*) FILTER (WHERE orders_cnt >= 2) / count(*), 2) AS returned_pct
FROM per_customer;

