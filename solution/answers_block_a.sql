-- 3. Средний чек заказа
--    Чек — свойство заказа: сначала сумма по заказу, потом среднее.
--    Контроль: 159.88
--
-- Разбор по словам:
--   WITH per_order AS (…) — весь смысл в двухступенчатости: первая ступень
--                          сворачивает строки до заказов, вторая усредняет
--                          заказы. Пропустишь первую — получишь среднюю
--                          СТРОКУ (139.97), а не средний ЧЕК.
--   sum(i.price + i.freight_value) — внутри заказа складываем цену товара
--                          и его доставку: покупатель платит за всё вместе.
--   count(*) AS lines    — строк в заказе; контрольное число уровня.
--   WHERE o.status = 'delivered' — чек только по доставленным, тем же,
--                          что и в выручке.
--   GROUP BY i.order_id  — одна группа = один заказ: per_order хранит
--                          одну строку на заказ с его полной суммой.
--   avg(order_total)     — среднее арифметическое готовых чеков; каждый
--                          заказ весит одинаково при любом числе строк.
--   round(…, 2)          — округлить до двух знаков: это деньги.
-- ------------------------------------------------------------
WITH per_order AS (
    SELECT
        i.order_id,
        sum(i.price + i.freight_value) AS order_total,
        count(*)                       AS lines,
        count(*)                       AS units   -- одна строка = одна единица
    FROM core.order_items i
    JOIN core.orders o USING (order_id)
    WHERE o.status = 'delivered'
    GROUP BY i.order_id
)
SELECT
    round(avg(order_total), 2) AS avg_check,
    round(avg(lines), 2)       AS avg_lines_per_order,
    round(avg(units), 2)       AS avg_units_per_order
FROM per_order;

