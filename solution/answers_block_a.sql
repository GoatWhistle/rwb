-- ------------------------------------------------------------
-- 1. Выручка и число заказов по месяцам, сен 2016 — авг 2018
--    Календарь генерируем: ноябрь 2016 пуст и без generate_series
--    выпадет из отчёта. Контроль: 24 строки, итого 13 221 498.11
--
-- Разбор по словам:
--   WITH months AS (…)   — WITH создаёт временную подтаблицу с именем,
--                          дальше к ней обращаемся как к обычной таблице.
--                          AS — «назовём её вот так». Здесь их две:
--                          months (календарь) и monthly (факты).
--   generate_series(a,b,шаг) — функция-генератор: ряд значений от a до b
--                          с данным шагом. Здесь 24 даты, по одной на месяц.
--                          interval '1 month' — шаг «один месяц».
--   ::date               — приведение типа: текст '2016-09-01' становится
--                          настоящей датой. Читается «как дата».
--   SELECT … AS month    — SELECT: «выбрать и показать эти колонки»;
--                          AS — дать колонке имя.
--   FROM core.orders o   — FROM: из какой таблицы брать строки. o — псевдоним:
--                          дальше o.status значит «колонка status заказов».
--   LEFT JOIN … USING (order_id) — JOIN приклеивает к заказу строки другой
--                          таблицы; USING — клеить по равенству order_id.
--                          LEFT — заказы без пары (775 штук без позиций)
--                          не выбрасывать, а оставить с пустыми значениями.
--                          Обычный JOIN их бы молча удалил.
--   date_trunc('month', x) — «обрезать» дату до начала месяца:
--                          2017-05-14 18:33 → 2017-05-01. Общая метка
--                          для группировки заказов одного месяца.
--   count(DISTINCT o.order_id) — посчитать только РАЗНЫЕ заказы: после
--                          склейки с позициями заказ из трёх товаров стал
--                          тремя строками и без DISTINCT посчитался бы трижды.
--   sum(…) FILTER (WHERE …) — сложить, но пропускать в сумму только строки,
--                          прошедшие условие: здесь только доставленные.
--   coalesce(x, 0)       — «если x пуст (NULL) — взять 0». У ноября 2016
--                          фактов нет, без coalesce была бы пустота, не ноль.
--   GROUP BY 1           — сгруппировать по первой колонке из SELECT
--                          (месяцу); count/sum считаются внутри групп.
--   финальный LEFT JOIN  — к полному календарю прикладываем факты;
--                          строка ноября обязана остаться.
--   ORDER BY m.month     — сортировка от раннего месяца к позднему.
-- ------------------------------------------------------------
WITH months AS (
    SELECT generate_series('2016-09-01'::date, '2018-08-01', interval '1 month')::date AS month
),
monthly AS (
    SELECT
        date_trunc('month', o.purchased_at)::date AS month,
        count(DISTINCT o.order_id)                AS orders_cnt,
        coalesce(sum(i.price) FILTER (WHERE o.status = 'delivered'), 0) AS revenue
    FROM core.orders o
    LEFT JOIN core.order_items i USING (order_id)
    GROUP BY 1
)
SELECT
    m.month,
    coalesce(t.orders_cnt, 0) AS orders_cnt,
    coalesce(t.revenue, 0)    AS revenue
FROM months m
LEFT JOIN monthly t USING (month)
ORDER BY m.month;

